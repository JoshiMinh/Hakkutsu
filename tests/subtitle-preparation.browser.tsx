import { createRoot } from "react-dom/client";
import { useRef } from "react";
import { SubtitleOverlay } from "../src/features/subtitles/shared/subtitle-overlay";
import { SubtitleScriptDrawer } from "../src/features/subtitles/shared/subtitle-script-drawer";
import { useSettingsStore } from "../src/features/settings/settings-store";
import { peekSubtitleTranslation } from "../src/features/subtitles/shared/subtitle-translations";
import type { SubtitleFetchResult, SubtitleSegment } from "../src/features/subtitles/shared/types";

function assert(value: unknown, message: string): asserts value { if (!value) throw new Error(message); }
const sleep = (ms: number) => new Promise(resolve => setTimeout(resolve, ms));
async function until(condition: () => boolean) {
  const end = performance.now() + 4000;
  while (!condition()) { if (performance.now() > end) throw new Error("Timed out"); await sleep(10); }
}
const cue = (start: number, text: string, duration = 2): SubtitleSegment => ({start,text,duration});
const track = (segments: SubtitleSegment[], language = "ja"): SubtitleFetchResult => ({videoId:"preparation",language,
  segments,fullText:segments.map(cue=>cue.text).join(" "),trackName:language,isAutoGenerated:false});

function fixtureVideo(fixture: HTMLElement) {
  const player = document.createElement("div"); player.className = "watch-video"; player.id = "movie_player";
  const video = document.createElement("video"), mount = document.createElement("div");
  Object.defineProperty(video,"readyState",{value:1});
  Object.defineProperty(video,"paused",{value:true});
  video.getBoundingClientRect=()=>({width:640,height:360}) as DOMRect;
  player.append(video,mount); fixture.replaceChildren(player);
  return {video,mount};
}

export function subtitlePreparationBrowserTests(fixture: HTMLElement): Array<[string,()=>Promise<void>]> {
  return [
    ["Native languages commit together while the target track downloads and use the same cue boundaries",async()=>{
      const {video,mount}=fixtureVideo(fixture), root=createRoot(mount);
      const saved=useSettingsStore.getState().settings;
      useSettingsStore.setState({settings:{...saved,subtitlesSecondaryEnabled:true,showFurigana:false}});
      const source=track([cue(0,"同期字幕",4)]), target=track([cue(0.2,"Synchronized captions",1),cue(1.2,"together",2.8)],"en");
      function Player({ready}:{ready:boolean}) {
        const ref=useRef(video);
        return <SubtitleOverlay isEnabled loading={false} error={null} subtitleData={source} secondaryData={ready?target:null}
          currentSegment={source.segments[0]} secondarySegment={null} secondaryTrackId="native-en" videoRef={ref}
          currentUrl="https://example.test/pair" onToggleEnabled={()=>{}} />;
      }
      let split=false;
      const observer=new MutationObserver(()=>{
        if(mount.querySelector(".hk-sub__bar")&&!mount.querySelector(".hk-sub__secondary-bar")?.textContent)split=true;
      });
      observer.observe(mount,{childList:true,subtree:true,characterData:true});
      try {
        root.render(<Player ready={false}/>);
        await until(()=>!!mount.querySelector(".hk-sub__status"));
        assert(!mount.querySelector(".hk-sub__bar"),"primary appeared while target track was still loading");
        root.render(<Player ready/>);
        await until(()=>mount.querySelector(".hk-sub__secondary-bar")?.textContent==="Synchronized captions together");
        assert(!split,"native languages appeared in separate commits");
        assert(mount.querySelector(".hk-sub__bar")?.textContent==="同期字幕","primary text changed");
        root.render(<SubtitleScriptDrawer isOpen nativePanel onClose={()=>{}} subtitleData={source} secondaryData={target}
          currentSegment={source.segments[0]} savedWords={new Set()} srsCardsMap={new Map()}/>);
        await until(()=>mount.querySelector(".hk-script-cue__secondary")?.textContent==="Synchronized captions together");
      } finally {observer.disconnect();root.unmount();useSettingsStore.setState({settings:saved});}
    }],
    ["Automatic translation appears with its source, preloads the next cue and never shows a stale language",async()=>{
      const {video,mount}=fixtureVideo(fixture),root=createRoot(mount);
      const saved=useSettingsStore.getState().settings, original=chrome.runtime.sendMessage;
      useSettingsStore.setState({settings:{...saved,targetLanguage:"en",subtitlesSecondaryEnabled:true,showFurigana:false}});
      const segments=[cue(0,"先読み字幕甲"),cue(4,"先読み字幕乙")],source=track(segments);
      const pending=new Map<string,(value:unknown)=>void>(); let calls=0;
      chrome.runtime.sendMessage=(async(message:{type:string;payload?:{text:string;targetLang:string}})=>{
        if(message.type!=="TRANSLATE_TEXT")return {payload:{cards:[]}};
        calls++;return new Promise<unknown>(resolve=>pending.set(`${message.payload!.targetLang}:${message.payload!.text}`,resolve));
      }) as typeof chrome.runtime.sendMessage;
      function Player({index}:{index:number}) {
        const ref=useRef(video);
        return <SubtitleOverlay isEnabled loading={false} error={null} subtitleData={source} currentSegment={segments[index]}
          secondaryTrackId="__auto_translate__" videoRef={ref} currentUrl="https://example.test/automatic" onToggleEnabled={()=>{}}/>;
      }
      try {
        root.render(<Player index={0}/>);
        await until(()=>pending.has("en:先読み字幕甲"));
        assert(!mount.querySelector(".hk-sub__bar"),"source appeared before its translation");
        pending.get("en:先読み字幕甲")!({type:"TRANSLATE_RESULT",payload:{translation:"First subtitle"}});
        await until(()=>mount.querySelector(".hk-sub__secondary-bar")?.textContent==="First subtitle");
        assert(mount.querySelector(".hk-sub__bar")?.textContent==="先読み字幕甲","wrong source paired with translation");
        await until(()=>pending.has("en:先読み字幕乙"));
        pending.get("en:先読み字幕乙")!({type:"TRANSLATE_RESULT",payload:{translation:"Second subtitle"}});
        await until(()=>peekSubtitleTranslation("先読み字幕乙","en")==="Second subtitle");
        root.render(<Player index={1}/>);
        await until(()=>mount.querySelector(".hk-sub__bar")?.textContent==="先読み字幕乙");
        assert(mount.querySelector(".hk-sub__secondary-bar")?.textContent==="Second subtitle","prefetched pair did not appear together");
        assert(calls===2,"prefetched cue requested translation again");
        useSettingsStore.setState({settings:{...saved,targetLanguage:"vi",subtitlesSecondaryEnabled:true,showFurigana:false}});
        await until(()=>pending.has("vi:先読み字幕乙"));
        assert(!mount.querySelector(".hk-sub__bar"),"old English translation remained while changing languages");
        pending.get("vi:先読み字幕乙")!({type:"TRANSLATE_RESULT",payload:{translation:"Phụ đề thứ hai"}});
        await until(()=>mount.querySelector(".hk-sub__secondary-bar")?.textContent==="Phụ đề thứ hai");
      } finally {
        root.unmount();
        for(const resolve of pending.values())resolve({type:"ERROR"});
        chrome.runtime.sendMessage=original;useSettingsStore.setState({settings:saved});
      }
    }],
    ["Netflix starts both full-track downloads concurrently and reveals them as one pair",async()=>{
      const {default:Netflix}=await import("../src/features/subtitles/netflix/netflix-subtitles");
      const {mount}=fixtureVideo(fixture),root=createRoot(mount);
      const saved=useSettingsStore.getState().settings, original=window.fetch;
      useSettingsStore.setState({settings:{...saved,targetLanguage:"vi",subtitlesEnabled:true,subtitlesSecondaryEnabled:true,showFurigana:false}});
      const pending=new Map<string,(value:Response)=>void>();
      window.fetch=(async(input:RequestInfo|URL)=>new Promise<Response>(resolve=>pending.set(String(input),resolve))) as typeof fetch;
      try {
        root.render(<Netflix/>);await until(()=>!!mount.querySelector(".hk-sub__container"));
        document.dispatchEvent(new CustomEvent("hakkutsu:netflix-synced-tracks",{detail:{videoId:"fixture-film",title:"Fixture",tracks:[
          {id:"ja",language:"ja",label:"Japanese",url:"https://example.test/netflix-ja"},
          {id:"vi",language:"vi",label:"Vietnamese",url:"https://example.test/netflix-vi"},
        ]}}));
        await until(()=>pending.size===2);
        pending.get("https://example.test/netflix-ja")!(new Response('<tt xmlns="http://www.w3.org/ns/ttml"><body><div><p begin="0s" end="3s">映画字幕</p></div></body></tt>'));
        await sleep(20);assert(!mount.querySelector(".hk-sub__bar"),"Netflix primary appeared before secondary download");
        pending.get("https://example.test/netflix-vi")!(new Response('<tt xmlns="http://www.w3.org/ns/ttml"><body><div><p begin="0.2s" end="3s">Phụ đề phim</p></div></body></tt>'));
        await until(()=>mount.querySelector(".hk-sub__secondary-bar")?.textContent==="Phụ đề phim");
        assert(mount.querySelector(".hk-sub__bar")?.textContent==="映画字幕","Netflix pair lost primary");
      } finally {root.unmount();window.fetch=original;useSettingsStore.setState({settings:saved});}
    }],
    ["Late translations after seeking cannot replace the current pair; failure keeps the source readable",async()=>{
      const {video,mount}=fixtureVideo(fixture),root=createRoot(mount);
      const saved=useSettingsStore.getState().settings, original=chrome.runtime.sendMessage;
      useSettingsStore.setState({settings:{...saved,targetLanguage:"en",subtitlesSecondaryEnabled:true,showFurigana:false}});
      const source=track([cue(0,"遅延字幕甲"),cue(100,"遅延字幕乙")]);
      const pending=new Map<string,(value:unknown)=>void>();
      chrome.runtime.sendMessage=(async(message:{type:string;payload?:{text:string}})=>{
        if(message.type!=="TRANSLATE_TEXT")return {payload:{cards:[]}};
        return new Promise<unknown>(resolve=>pending.set(message.payload!.text,resolve));
      }) as typeof chrome.runtime.sendMessage;
      function Player({index}:{index:number}) {
        const ref=useRef(video);
        return <SubtitleOverlay isEnabled loading={false} error={null} subtitleData={source} currentSegment={source.segments[index]}
          secondaryTrackId="__auto_translate__" videoRef={ref} currentUrl="https://example.test/late" onToggleEnabled={()=>{}}/>;
      }
      try {
        root.render(<Player index={0}/>);await until(()=>pending.has("遅延字幕甲"));
        video.currentTime=100;root.render(<Player index={1}/>);await until(()=>pending.has("遅延字幕乙"));
        pending.get("遅延字幕甲")!({type:"TRANSLATE_RESULT",payload:{translation:"Obsolete translation"}});
        await sleep(20);assert(!mount.textContent?.includes("Obsolete translation"),"late reply appeared after seek");
        assert(!mount.querySelector(".hk-sub__bar"),"new source appeared before its matching translation");
        pending.get("遅延字幕乙")!({type:"ERROR"});
        await until(()=>mount.querySelector(".hk-sub__bar")?.textContent==="遅延字幕乙");
        assert(!mount.querySelector(".hk-sub__secondary-bar"),"failed translation kept a stale subtitle");
        assert(!!mount.querySelector(".hk-sub__status"),"translation failure was silent");
      } finally {root.unmount();for(const resolve of pending.values())resolve({type:"ERROR"});chrome.runtime.sendMessage=original;useSettingsStore.setState({settings:saved});}
    }],
    ["YouTube downloads the complete source and translated tracks together",async()=>{
      const {default:YouTube}=await import("../src/features/subtitles/youtube/youtube-subtitles");
      const {mount}=fixtureVideo(fixture),root=createRoot(mount);
      const saved=useSettingsStore.getState().settings, original=window.fetch;
      useSettingsStore.setState({settings:{...saved,targetLanguage:"vi",subtitlesEnabled:true,subtitlesSecondaryEnabled:true,showFurigana:false}});
      const pending=new Map<string,(value:Response)=>void>();
      window.fetch=(async(input:RequestInfo|URL)=>new Promise<Response>(resolve=>pending.set(String(input),resolve))) as typeof fetch;
      try {
        root.render(<YouTube/>);await until(()=>!!mount.querySelector(".hk-sub__container"));
        document.dispatchEvent(new CustomEvent("hakkutsu:youtube-synced-tracks",{detail:{videoId:"fixture-youtube",title:"Fixture",tracks:[
          {id:"ja",language:"ja",label:"Japanese",url:"https://example.test/youtube-captions?fmt=json3",isAutoGenerated:false},
        ]}}));
        await until(()=>pending.size===2);
        const sourceUrl=[...pending.keys()].find(url=>!new URL(url).searchParams.has("tlang"))!;
        const targetUrl=[...pending.keys()].find(url=>new URL(url).searchParams.get("tlang")==="vi")!;
        assert(!!sourceUrl&&!!targetUrl,"YouTube did not request a full translated track");
        pending.get(sourceUrl)!(new Response(JSON.stringify({events:[{tStartMs:0,dDurationMs:3000,segs:[{utf8:"動画字幕"}]}]})));
        await sleep(20);assert(!mount.querySelector(".hk-sub__bar"),"YouTube primary appeared before target track");
        pending.get(targetUrl)!(new Response(JSON.stringify({events:[{tStartMs:200,dDurationMs:2800,segs:[{utf8:"Phụ đề video"}]}]})));
        await until(()=>mount.querySelector(".hk-sub__secondary-bar")?.textContent==="Phụ đề video");
        assert(mount.querySelector(".hk-sub__bar")?.textContent==="動画字幕","YouTube pair lost primary");
      } finally {root.unmount();window.fetch=original;useSettingsStore.setState({settings:saved});}
    }],
  ];
}
