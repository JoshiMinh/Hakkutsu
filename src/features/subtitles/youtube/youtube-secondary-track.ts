import type { SubtitleTrackOption } from "~/features/subtitles/shared/select-subtitles-modal";

/** Prefer a native target track; otherwise download YouTube's complete translated track. */
export function chooseYouTubeSecondaryTrack(tracks: SubtitleTrackOption[], primary: SubtitleTrackOption | undefined, language: string): SubtitleTrackOption | null {
  const native = tracks.find(track => track.id !== primary?.id && track.languageCode.split("-")[0] === language.split("-")[0]);
  if (native) return native;
  if (!primary?.url) return null;
  const url = new URL(primary.url);
  url.searchParams.set("tlang", language);
  return { id: `yt-auto-translate-${language}`, name: `${language} (Auto Translate)`, languageCode: language,
    url: url.href, isAutoGenerated: true };
}
