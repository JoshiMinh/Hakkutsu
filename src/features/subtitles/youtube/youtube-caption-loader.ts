import type { SubtitleSegment } from "~/features/subtitles/shared/types";
import { parseYouTubeJson3, parseYouTubeTimedTextXml } from "~/features/subtitles/shared/subtitle-parsers";
import { buildSmartCues } from "~/features/subtitles/shared/smart-cue";

let requestSequence = 0;

export function requestPageCaptionContent(url: string, signal?: AbortSignal): Promise<string> {
  return new Promise((resolve, reject) => {
    if (signal?.aborted) { reject(signal.reason); return; }
    const requestId = `caption-${Date.now()}-${++requestSequence}`;
    const finish = (text?: string, error?: string) => {
      clearTimeout(timer);
      document.removeEventListener("hakkutsu:youtube-caption-content", listener);
      signal?.removeEventListener("abort", abort);
      if (error) reject(new Error(error));
      else resolve(text || "");
    };
    const abort = () => {
      document.dispatchEvent(new CustomEvent("hakkutsu:cancel-youtube-caption-content", { detail: { requestId } }));
      finish(undefined, "Caption request cancelled");
    };
    const listener = (event: Event) => {
      const result = (event as CustomEvent).detail;
      if (result?.requestId !== requestId) return;
      finish(typeof result.text === "string" ? result.text : "", result.error);
    };
    const timer = setTimeout(() => finish(undefined, "YouTube caption request timed out"), 9000);
    document.addEventListener("hakkutsu:youtube-caption-content", listener);
    signal?.addEventListener("abort", abort, { once: true });
    document.dispatchEvent(new CustomEvent("hakkutsu:request-youtube-caption-content", { detail: { requestId, url } }));
  });
}

/** Start fallback routes after a short head start, rather than serial 8s waits. */
function loadCaptionUrl(url: string, parse: (text: string) => SubtitleSegment[], parent?: AbortSignal): Promise<SubtitleSegment[]> {
  return new Promise((resolve, reject) => {
    const controller = new AbortController();
    const started = new Set<number>();
    const timers: ReturnType<typeof setTimeout>[] = [];
    let settled = false, failures = 0;
    let lastError: unknown = new Error("No readable captions");
    const finish = (segments?: SubtitleSegment[], error?: unknown) => {
      if (settled) return;
      settled = true;
      for (const timer of timers) clearTimeout(timer);
      parent?.removeEventListener("abort", abort);
      controller.abort();
      if (segments) resolve(segments); else reject(error);
    };
    const abort = () => finish(undefined, parent?.reason || new DOMException("Cancelled", "AbortError"));
    if (parent?.aborted) { abort(); return; }
    const transports = [
      async () => {
        const response = await fetch(url, { credentials: "include", signal: controller.signal });
        if (!response.ok) throw new Error(`HTTP ${response.status}`);
        return response.text();
      },
      () => requestPageCaptionContent(url, controller.signal),
      async () => {
        const response = await chrome.runtime.sendMessage({ type: "FETCH_TIMEDTEXT_URL", payload: { url } });
        if (!response?.payload?.success) throw new Error(response?.payload?.error || "Caption request failed");
        return String(response.payload.text || "");
      },
    ];
    const start = (index: number) => {
      if (settled || started.has(index) || index >= transports.length) return;
      started.add(index);
      void transports[index]().then(text => {
        if (settled) return;
        const segments = parse(text);
        if (!segments.length) throw new Error("No readable captions");
        finish(segments);
      }).catch(error => {
        if (settled) return;
        lastError = error;
        if (++failures === transports.length) finish(undefined, lastError);
        else start(index + 1);
      });
    };
    parent?.addEventListener("abort", abort, { once: true });
    timers.push(setTimeout(() => start(1), 200), setTimeout(() => start(2), 400),
      setTimeout(() => finish(undefined, new Error("Caption request timed out")), 8000));
    start(0);
  });
}

export async function loadYouTubeCaptionTrack(track: {
  url?: string; name: string; isAutoGenerated?: boolean;
}, signal?: AbortSignal): Promise<SubtitleSegment[]> {
  if (!track.url) throw new Error("Missing subtitle track URL");
  const urls = [track.url];
  const jsonUrl = new URL(track.url, window.location.href);
  jsonUrl.searchParams.set("fmt", "json3");
  if (jsonUrl.toString() !== track.url) urls.push(jsonUrl.toString());
  let lastError = "The server returned no readable captions";
  const parse = (text: string): SubtitleSegment[] => {
    if (!text.trim()) return [];
    const segments = text.trim().startsWith("{") ? parseYouTubeJson3(text) : parseYouTubeTimedTextXml(text);
    return buildSmartCues(segments, Boolean(track.isAutoGenerated));
  };
  for (const url of urls) {
    signal?.throwIfAborted();
    try { return await loadCaptionUrl(url, parse, signal); }
    catch (error) { signal?.throwIfAborted(); lastError = error instanceof Error ? error.message : String(error); }
  }
  throw new Error(`Could not load ${track.name}: ${lastError}`);
}
